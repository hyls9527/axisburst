"""AB-100 座体外壳 —— 总装最底部的承力件。

外形要点：宽底法兰（螺栓圈）+ 带滚花的柱身 + 一圈薄散热片 + 顶部定位凸台 + 内腔。
散热片和滚花是「机加工件」观感的主要来源，光靠圆柱会很玩具。
"""

from __future__ import annotations

import partkit as kit

# ---------------------------------------------------------------- 零件档案

ID = "housing"
PN = "AB-100"
LABEL = "座体外壳"
LABEL_EN = "HOUSING"
GROUP = "机体组"
ORDER = 0
QTY = 1
Z = 0.0                      # 装配时沿轴的位置（局部 z=0 落位）
MATERIAL = "ZG270-500 铸钢"
PROCESS = "铸造 + 车削 + 滚花"

# 设计参数（模块自己知道的意图，和实测包围盒一起进清单）
PARAMS = [
    ("底法兰外径", "Ø3.84"),
    ("上盘外径", "Ø3.76"),
    ("总高", "1.30"),
    ("内孔", "Ø1.80"),
    ("辐条", "24 × 0.04"),
    ("滚花带", "72 齿 × 0.02 深"),
    ("盘面螺栓", "6 × M12"),
    ("加强筋", "6 片 × 0.05"),
]


def build(col, kit_ctx=None):
    # 回转轮廓：(半径, 高度)，首尾必须落在旋转轴上
    profile = [
        (0.00, -0.620),
        (1.92, -0.620),      # 底面
        (1.92, -0.460),      # 底法兰外圆
        (1.86, -0.420),      # 倒角
        (1.60, -0.400),      # 收进柱身
        (1.60, 0.100),       # 柱身（滚花段）
        (1.88, 0.160),       # 上盘底缘
        (1.88, 0.260),       # 上盘外圆
        (1.80, 0.300),       # 盘缘倒角
        (1.14, 0.300),       # 上盘顶面（放射辐条长在这上面）
        (1.14, 0.180),       # 内孔台阶
        (0.90, 0.140),
        (0.90, -0.340),      # 主内孔
        (0.56, -0.400),
        (0.56, -0.620),
        (0.00, -0.620),
    ]
    kit.lathe(col, "housing_body", profile, segments=192, bevel=0.014, bevel_segments=3)

    # 柱身滚花
    kit.knurl(
        col, "housing_knurl",
        radius=1.600, z0=-0.340, z1=0.060,
        count=72, depth=0.020, width=0.030,
    )

    # 上盘面的放射辐条 —— 俯视时的主要纹理
    kit.radial_ribs(
        col, "housing_ribs",
        count=24, r_in=1.220, r_out=1.780,
        z=0.300, height=0.055, thickness=0.042,
    )

    # 上盘面螺栓圈（俯视可见）
    kit.bolt_ring(
        col, "housing_bolt",
        count=6, ring_r=1.840, phase=0.2618,
        head_r=0.100, head_h=0.075, shank_r=0.058, shank_h=0.180,
        z=0.300,
    )

    # 加强筋（法兰到柱身之间）
    kit.gussets(
        col, "housing_rib",
        count=6, r_in=1.620, r_out=1.900,
        z0=-0.460, z1=-0.120,
        thickness=0.052, phase=0.5236,
    )

    return col
